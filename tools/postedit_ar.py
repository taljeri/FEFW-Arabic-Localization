def apply_glossary(text):
    for ja, variants in GLOSSARY.items():
        canon = variants[0]
        for v in variants[1:]:
            if v and v != canon and v in text:
                text = text.replace(v, canon)
    for bad, good in _IDIOM_FIXES:
        if bad in text:
            text = text.replace(bad, good)
    return text


def clean(text):
    if not text:
        return text
    for rx, rep in _SPACES:
        text = rx.sub(rep, text)
    return text.strip()


def speaker_gender(jp_line):
    if _FEM_1ST.search(jp_line):
        return 'f'
    if _MALE_1ST.search(jp_line):
        return 'm'
    if _NEUTRAL_1ST.search(jp_line):
        return 'n'
    return None


def agree_with_speaker(ar_text, gender):
    if not ar_text or gender not in ('f', 'm'):
        return ar_text
    pairs = _FEM_1ST_PAIRS if gender == 'f' else _MASC_1ST_PAIRS
    seen = set()
    for a, b in pairs:
        if a == b or a in seen:
            continue
        seen.add(a)
        if gender == 'f':
            ar_text = _re.sub(_re.escape(a) + r'(?!\u0629)', b, ar_text)
        else:
            ar_text = ar_text.replace(a, b)
    return ar_text


def postedit(text, gender=None):
    if not text:
        return text
    t = clean(text)
    t = apply_glossary(t)
    if gender in ('f', 'm'):
        t = agree_with_speaker(t, gender)
    return t
